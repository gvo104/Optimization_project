from dataclasses import dataclass, field


# ---------------------------------------------------------------------------
#  Конфигурации алгоритмов оптимизации
# ---------------------------------------------------------------------------

@dataclass
class GAConfig:
    """Параметры генетического алгоритма"""
    pop_size: int = 50            # размер популяции
    generations: int = 100        # число поколений
    mutation_rate: float = 0.15   # вероятность мутации одного гена
    crossover_rate: float = 0.8   # вероятность кроссовера
    elite_size: int = 2           # число элитных особей, переходящих без изменений
    tournament_size: int = 3      # размер турнира при селекции


@dataclass
class PSOConfig:
    """Параметры метода роя частиц"""
    num_particles: int = 30       # количество частиц
    iterations: int = 100         # число итераций
    w: float = 0.7                # коэффициент инерции
    c1: float = 1.5               # когнитивный коэффициент (притяжение к лучшей точке частицы)
    c2: float = 1.5               # социальный коэффициент (притяжение к глобально лучшей точке)
    v_max_t: float = 60           # максимальная скорость изменения времени пробуждения (t_w)


@dataclass
class ACOConfig:
    """Параметры муравьиного алгоритма"""
    num_ants: int = 30            # число муравьёв в итерации
    iterations: int = 50          # число итераций
    evaporation: float = 0.1     # коэффициент испарения феромона (0..1)
    alpha: float = 1.0           # вес феромона при выборе пути
    beta: float = 2.0            # вес эвристической информации при выборе пути
    q0: float = 0.5              # вероятность выбора строго по максимуму (эксплуатация)
    step_minutes: int = 5        # шаг дискретизации времени пробуждения (минут)


@dataclass
class SimAnnealingConfig:
    """Параметры имитации отжига"""
    initial_temp: float = 1000.0  # начальная температура
    cooling_rate: float = 0.995   # коэффициент охлаждения (умножается на каждом шаге)
    iterations_per_temp: int = 10 # число итераций при фиксированной температуре
    min_temp: float = 0.1         # минимальная температура, при достижении которой остановка
    step_std_t: float = 30        # стандартное отклонение возмущения времени пробуждения (минут)


# ---------------------------------------------------------------------------
#  Конфигурация самой задачи "Идеальный рабочий день"
# ---------------------------------------------------------------------------

@dataclass
class ScheduleProblemConfig:
    """
    Все параметры, определяющие расписание и целевую функцию.
    Изменяя их, можно кардинально менять ландшафт оптимизируемой функции.
    """

    # --------------- Длительности блоков дня (минуты) ---------------
    M: int = 60          # утренние сборы
    C: int = 20          # дорога на работу
    L: int = 60          # обеденный перерыв
    W_work: int = 480    # чистое рабочее время (без обеда)
    W_study: int = 120   # длительность учёбы
    D_back: int = 30     # дорога с работы домой
    E: int = 45          # вечерний отдых перед сном
    # Сумма всех блоков от пробуждения до отбоя = 815 минут (проверьте при изменении)
    # Тогда длительность сна T_sleep = 1440 - 815 = 625 минут (постоянна!)

    # ----------------------- Параметры сна -------------------------
    T_min_sleep: int = 420        # минимально допустимый сон (иначе 1e12 штрафа)
    T_best_sleep: int = 540       # желаемая длительность сна (при меньшем сне – штраф недосыпа)
    Cycle: int = 90               # длительность одного цикла сна (фаза пробуждения)

    # -------------------- Ограничения на работу --------------------
    Work_start_early: int = 540   # самое раннее допустимое начало работы (09:00)
    Work_start_late: int = 660    # самое позднее допустимое начало работы (11:00)
    Ideal_start: int = 570        # идеальное время начала работы (09:30)

    # ------------------- Параметры вечерней учёбы ------------------
    Study_ineffective_after: int = 1145  # время (минуты от полуночи), после которого учёба считается
                                         # менее эффективной (19:05)
    Study_eff_drop: float = 0.5          # коэффициент падения эффективности (0.5 = половина пользы)

    # -------------------- Веса штрафов в целевой функции --------------------
    # Их соотношение определяет, насколько важно соблюсти каждое из условий.
    # Ниже подобраны так, чтобы создать несколько привлекательных, но
    # конкурирующих локальных минимумов.
    w_phase: float = 10     # вес штрафа за фазу сна
    w_debt: float = 1      # вес штрафа за недосып
    w_work: float = 2       # вес штрафа за отклонение начала работы от идеала
    w_study: float = 3      # вес штрафа за позднюю (неэффективную) учёбу

    # --------------- Вложенные конфигурации алгоритмов ---------------
    ga: GAConfig = field(default_factory=GAConfig)
    pso: PSOConfig = field(default_factory=PSOConfig)
    aco: ACOConfig = field(default_factory=ACOConfig)
    annealing: SimAnnealingConfig = field(default_factory=SimAnnealingConfig)